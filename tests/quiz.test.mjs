import test from 'node:test';
import assert from 'node:assert/strict';
import * as quiz from '../public/js/quiz.js';
const mcq={id:'q1',lesson_id:'world-mars',type:'mcq',options:['a','b'],answer:1,explanation:'Because b.'};
test('written answers return an ungraded rubric, never a fabricated score',()=>{
  const written={...mcq,type:'written',rubric:['Evidence','Uncertainty']};
  for(const answer of ['', 'anything',null]) assert.deepEqual(quiz.gradeQuestion(written,answer),{correct:null,score:null,explanation:written.explanation,rubric:written.rubric});
  const result=quiz.gradeQuestion(written,''); result.rubric.push('no mutation'); assert.equal(written.rubric.length,2);
  assert.throws(()=>quiz.gradeQuestion({...written,rubric:'bad'},''));
  assert.throws(()=>quiz.gradeQuestion({...mcq,type:'unknown'},0));
  assert.throws(()=>quiz.gradeQuestion({...mcq,explanation:8},0));
});
test('review scheduler uses days, bounds quality and resets after forgetting',()=>{
  const now=1000,day=86400000;
  assert.deepEqual(quiz.scheduleReview(null,0,now),{due:now+day,interval:1,repetitions:0});
  const first=quiz.scheduleReview(null,2,now); assert.deepEqual(first,{due:now+day,interval:1,repetitions:1});
  const second=quiz.scheduleReview(first,2,now); assert.equal(second.interval,3); assert.equal(second.repetitions,2);
  assert.equal(quiz.scheduleReview(second,2,now).interval,6);
  assert.equal(quiz.scheduleReview(second,1,now).interval,3);
  assert.deepEqual(quiz.scheduleReview(second,0,now),{due:now+day,interval:1,repetitions:0});
  for(const quality of [-1,3,0.5,'2',NaN]) assert.throws(()=>quiz.scheduleReview(null,quality,now));
  for(const previous of [{}, {due:0,interval:-1,repetitions:0},{due:0,interval:1,repetitions:0.1}]) assert.throws(()=>quiz.scheduleReview(previous,1,now));
  assert.throws(()=>quiz.scheduleReview(null,2,Infinity));
});
const bank=Array.from({length:30},(_,i)=>({...mcq,id:'q'+i,lesson_id:i<15?'world-mars':'system-trappist-1'}));
test('selection filters, samples without replacement, bounds work and never mutates input',()=>{
  const frozen=Object.freeze(bank.map(q=>Object.freeze({...q}))),before=JSON.stringify(frozen);
  const selected=quiz.selectQuestions(frozen,{count:10,lessonIds:['world-mars']});
  assert.equal(selected.length,10); assert.equal(new Set(selected.map(q=>q.id)).size,10); assert.ok(selected.every(q=>q.lesson_id==='world-mars'));
  assert.equal(JSON.stringify(frozen),before);
  assert.equal(quiz.selectQuestions(frozen,{count:100}).length,30);
  assert.deepEqual(quiz.selectQuestions(frozen,{count:0}),[]);
  assert.deepEqual(quiz.selectQuestions(frozen,{count:10,lessonIds:[]}),[]);
  assert.deepEqual(quiz.selectQuestions([],{count:5}),[]);
  for(const count of [-1,Infinity,1.5,'5',1001]) assert.throws(()=>quiz.selectQuestions(bank,{count}));
  assert.throws(()=>quiz.selectQuestions([bank[0],bank[0]],{count:1}));
  assert.throws(()=>quiz.selectQuestions(bank,{count:1,lessonIds:'world-mars'}));
});
test('exam selects at most twenty balanced questions with worlds weighted above systems and no keys',()=>{
  const mixed=[...bank,...Array.from({length:20},(_,i)=>({...mcq,id:'other'+i,lesson_id:'foundation-'+i}))];
  const before=JSON.stringify(mixed),exam=quiz.createExam(mixed,1000);
  assert.deepEqual(Object.keys(exam).sort(),['answers','endsAt','questionIds','startedAt','submitted']);
  assert.deepEqual(exam.answers,{}); assert.equal(exam.startedAt,1000); assert.equal(exam.endsAt,3001000); assert.equal(exam.submitted,false);
  assert.equal(exam.questionIds.length,20); assert.equal(new Set(exam.questionIds).size,20);
  const picked=mixed.filter(q=>exam.questionIds.includes(q.id));
  assert.ok(picked.filter(q=>q.lesson_id.startsWith('world')).length>picked.filter(q=>q.lesson_id.startsWith('system')).length);
  assert.ok(picked.some(q=>q.lesson_id.startsWith('foundation'))); assert.ok(picked.some(q=>q.lesson_id.startsWith('system')));
  assert.equal(JSON.stringify(mixed),before);
  assert.deepEqual(quiz.createExam([],1000).questionIds,[]);
  assert.equal(quiz.createExam(bank,1000).questionIds.length,20);
  assert.throws(()=>quiz.createExam(bank,-1));
  const sparse=[{...mcq,id:'world',lesson_id:'mars',rule_refs:['3.a.i']},...Array.from({length:8},(_,i)=>({...mcq,id:'s'+i,lesson_id:'trappist-1',rule_refs:['3.a.ii']}))];
  assert.deepEqual(quiz.createExam(sparse,1000).questionIds,['world']);
  const diverse=Array.from({length:8},(_,i)=>Array.from({length:10},(_,j)=>({...mcq,id:`w${i}-${j}`,lesson_id:'world-'+i}))).flat();
  const ids=quiz.createExam(diverse,1000).questionIds;
  assert.equal(new Set(diverse.filter(q=>ids.includes(q.id)).map(q=>q.lesson_id)).size,8);
});
import {defaultState,exportState,importState} from '../public/js/storage.js';
test('exam countdown survives serialized reload, reaches zero and stops on submission',()=>{
  const exam=quiz.createExam(bank,1000); exam.answers[exam.questionIds[0]]=1;
  const restored=importState(exportState({...defaultState(),exam})).exam;
  assert.deepEqual(restored,exam);
  assert.equal(quiz.remainingSeconds(restored,1000),3000);
  assert.equal(quiz.remainingSeconds(restored,2001),2999);
  assert.equal(quiz.remainingSeconds(restored,3000999),1);
  assert.equal(quiz.remainingSeconds(restored,3001000),0);
  assert.equal(quiz.remainingSeconds(restored,4001000),0);
  assert.equal(quiz.remainingSeconds(restored,0),3000);
  assert.equal(quiz.remainingSeconds({...restored,submitted:true},1000),0);
  assert.equal(quiz.remainingSeconds(null,1000),0);
  assert.throws(()=>quiz.remainingSeconds(restored,NaN));
  assert.throws(()=>quiz.remainingSeconds({...restored,endsAt:Infinity},1000));
});
test('MCQ grades only an integer option index with explicit explanation',()=>{
  assert.deepEqual(quiz.gradeQuestion(mcq,1),{correct:true,score:1,explanation:'Because b.'});
  assert.deepEqual(quiz.gradeQuestion(mcq,0),{correct:false,score:0,explanation:'Because b.'});
  assert.deepEqual(quiz.gradeQuestion(mcq,null),{correct:false,score:0,explanation:'Because b.'});
  for(const value of ['1',-1,2,0.5,NaN]) assert.throws(()=>quiz.gradeQuestion(mcq,value));
  assert.throws(()=>quiz.gradeQuestion({...mcq,answer:9},0));
});
